import assert from 'node:assert/strict';
import { AnsiParser } from '../web/src/lib/ansi.ts';
import { guessTarget } from '../web/src/lib/roomText.ts';
const p = new AnsiParser();
const a = p.parse('x\x1b[3');
const b = p.parse('1mred\x1b[38;5;196mxt\x1b[0m');
assert.deepEqual(a.map((s) => s.text), ['x']);
assert.equal(b[0].text, 'red'); assert.ok(b[0].fg);
assert.equal(b[1].fg, 'rgb(255,0,0)');
assert.equal(guessTarget('( 2) A large brown rat is here.').kw, 'rat');
assert.equal(guessTarget('( 2) A large brown rat is here.').count, 2);
assert.equal(guessTarget('[AFK] (W) Kaof the Ninja is here.').kw, 'kaof');
assert.equal(guessTarget('A loaf of bread lies here.').kw, 'bread');
const kw = (l: string) => guessTarget(l).kw;
assert.equal(kw('     The blackboard has a review of hunting and combat training lessons.'), 'blackboard');
assert.equal(kw('A fountain gushes water from a stone basin here.'), 'fountain');
assert.equal(kw('A pair of leather boots lies here.'), 'boots');
assert.equal(kw('Commander Dahr teaches combat to new recruits.'), 'commander');
assert.equal(kw('(Player) Fennic the Shaman.'), 'fennic');
assert.equal(kw('A glass of milk sits on the bar.'), 'milk');
assert.equal(kw('A large rat is here, sniffing.'), 'rat');
assert.equal(kw('A wise old owl watches you closely.'), 'owl');
console.log('ansi tests passed');
